/**
 * src/engine/image-docs.ts
 *
 * Builds docs/image-credits.md and docs/image-review.md from the picture manifest and the
 * question mapping. Pure: returns text. tools/images/build-images.mjs writes the files and a test
 * checks they match, so the docs cannot go stale.
 */
import type { PictureManifest, QuestionImageMapping } from "./question-images.ts";

export interface QuestionInfo {
  id: string;
  version: string;
  text: string;
}

export interface TodoEntry {
  wanted: string;
  pageUrl: string;
  reason: string;
}

const cell = (text: string): string => text.replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ");
const GENERATED = "<!-- Generated by tools/images/build-images.mjs from data/images/*.json. Do not edit by hand. -->";

export function buildCredits(manifest: PictureManifest, mapping: QuestionImageMapping): string {
  const L: string[] = ["# Image credits", "", GENERATED, ""];
  L.push(
    "The pictures in civics practice are works from official U.S. federal sources. Each one is used only because its own record states its rights (public domain, U.S. government work, CC0, or \"no known restrictions on publication\"). The rights text below is copied word for word from the source record on the download date.",
    "",
    "Using these pictures does not mean the Library of Congress, any other agency or any person in them endorses Language Lab. Language Lab is not affiliated with USCIS or any government agency.",
    ""
  );
  L.push(`${manifest.images.length} pictures.`, "");
  for (const p of manifest.images) {
    const questions = Object.entries(mapping.questions)
      .filter(([, id]) => id === p.id)
      .map(([q]) => q);
    L.push(`## ${cell(p.title)}`, "");
    L.push(`- **Picture id:** \`${p.id}\` (file \`${p.file}\`)`);
    L.push(`- **Creator:** ${cell(p.creator)}`);
    L.push(`- **Date:** ${cell(p.date)}`);
    L.push(`- **Source page:** <${p.sourcePageUrl}>`);
    L.push(`- **File downloaded from:** <${p.fileUrl}> on ${p.downloadedOn} (SHA-256 of the download: \`${p.sha256}\`)`);
    L.push(`- **Rights statement:** "${p.rights}"`);
    L.push(`- **Used for questions:** ${questions.length === 0 ? "none" : questions.join(", ")}`);
    L.push("");
  }
  return L.join("\n");
}

export function buildReview(manifest: PictureManifest, mapping: QuestionImageMapping, questions: readonly QuestionInfo[]): string {
  const byId = new Map(manifest.images.map((p) => [p.id, p]));
  const L: string[] = ["# Image review", "", GENERATED, ""];
  L.push(
    "Every pairing of a civics question and a picture, for the owner to check. `question-images.json` is marked `needsHumanReview`: a picture is shown only after the answer is graded and in Study first, but a wrong pairing would still mislead. Check that each picture fits the question and does not suggest a wrong answer.",
    ""
  );
  const mapped = questions.filter((q) => q.id in mapping.questions);
  L.push(`${mapped.length} of ${questions.length} questions have a picture.`, "");
  L.push("| Question | Text | Picture | Caption | Source | Rights |", "|---|---|---|---|---|---|");
  for (const q of mapped) {
    const p = byId.get(mapping.questions[q.id] as string);
    if (p === undefined) continue;
    L.push(
      `| ${q.id} | ${cell(q.text)} | ![${cell(p.alt)}](../public/images/civics/${p.file}) \`public/images/civics/${p.file}\` | ${cell(p.caption)} | <${p.sourcePageUrl}> | ${cell(p.rights)} |`
    );
  }
  const without = questions.filter((q) => !(q.id in mapping.questions));
  L.push("", "## Questions without a picture", "");
  L.push(without.map((q) => q.id).join(", "), "");
  return L.join("\n");
}

export function buildTodo(todo: readonly TodoEntry[]): string {
  const L: string[] = ["# Image to-do", "", GENERATED, ""];
  L.push(
    "Pictures I wanted but could not use. No other source was substituted. Fetch these by hand, check the rights statement on the page, and add them to `data/images/picks.json`.",
    ""
  );
  if (todo.length === 0) {
    L.push("None.", "");
    return L.join("\n");
  }
  L.push("| Wanted | Page | Why it was not saved |", "|---|---|---|");
  for (const t of todo) L.push(`| ${cell(t.wanted)} | <${t.pageUrl}> | ${cell(t.reason)} |`);
  L.push("");
  return L.join("\n");
}
