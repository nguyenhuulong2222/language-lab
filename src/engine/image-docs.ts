/**
 * src/engine/image-docs.ts
 *
 * Builds docs/image-credits.md and docs/image-review.md from the picture manifest and the
 * question mapping. Pure: returns text. tools/images/build-images.mjs writes the files and a test
 * checks they match, so the docs cannot go stale.
 */
import type { IllustrationManifest } from "./illustrations.ts";
import type { PictureManifest, QuestionImageMapping } from "./question-images.ts";

export interface QuestionInfo {
  id: string;
  version: string;
  text: string;
}

/** A question of a picture class that still has no picture (data/images/misses.json). */
export interface MissEntry {
  questions: string[];
  wanted: string;
  searched: string;
  why: string;
}
export interface TodoEntry {
  wanted: string;
  pageUrl: string;
  reason: string;
}

const cell = (text: string): string => text.replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ");
const GENERATED = "<!-- Generated by tools/images/build-images.mjs from data/images/*.json. Do not edit by hand. -->";

export function buildCredits(manifest: PictureManifest, mapping: QuestionImageMapping, illustrations: IllustrationManifest = { images: [] }): string {
  const L: string[] = ["# Image credits", "", GENERATED, ""];
  L.push(
    "The pictures in civics practice are works from official U.S. federal sources. Each one is used only because its own record states its rights (public domain, U.S. government work, CC0, \"no known restrictions on publication\", or a National Archives Catalog record whose use and access restriction are both \"Unrestricted\"). The rights text below is the source record's own statement, copied as it was on the download date. Smithsonian records give it in their \"Restrictions & Rights\" field.",
    "",
    "Using these pictures does not mean the Library of Congress, any other agency or any person in them endorses Language Lab. Language Lab is not affiliated with USCIS or any government agency.",
    ""
  );
  L.push(`${manifest.images.length} pictures.`, "");
  for (const p of manifest.images) {
    const questions = Object.entries(mapping.questions)
      .filter(([, id]) => id === p.id)
      .map(([q]) => q);
    L.push(`## ${cell(p.title)}`, "");
    L.push(`- **Picture id:** \`${p.id}\` (file \`${p.file}\`)`);
    L.push(`- **Creator:** ${cell(p.creator)}`);
    L.push(`- **Date:** ${cell(p.date)}`);
    L.push(`- **Source page:** <${p.sourcePageUrl}>`);
    L.push(`- **File downloaded from:** <${p.fileUrl}> on ${p.downloadedOn} (SHA-256 of the download: \`${p.sha256}\`)`);
    if (p.edit !== undefined) L.push(`- **Edit:** ${cell(p.edit)}`);
    L.push(`- **Rights statement (copied from the source record):** "${p.rights}"`);
    L.push(`- **Used for questions:** ${questions.length === 0 ? "none" : questions.join(", ")}`);
    L.push("");
  }
  L.push("# AI-generated illustrations", "");
  L.push(
    "Some ideas (CONCEPT questions only, such as the rule of law) may have an illustration made by an OpenAI image model from prompts in `data/images/illustration-prompts.json`. Each one is labelled \"AI-generated illustration\" on screen and is shown only after the owner has reviewed it. They never show a real person, event or document.",
    ""
  );
  if (illustrations.images.length === 0) L.push("None made yet.", "");
  for (const e of illustrations.images) {
    L.push(`## ${cell(e.caption)}`, "");
    L.push(`- **Illustration id:** \`${e.id}\` (file \`${e.file}\`)`);
    L.push(`- **Model:** ${cell(e.model)}, made on ${e.date} (SHA-256: \`${e.sha256}\`)`);
    L.push(`- **Reviewed by the owner:** ${e.reviewed ? "yes (shown in the app)" : "not yet (not shown)"}`);
    L.push(`- **Used for questions:** ${e.questions.join(", ")}`);
    L.push("");
  }
  return L.join("\n");
}

export function buildReview(
  manifest: PictureManifest,
  mapping: QuestionImageMapping,
  questions: readonly QuestionInfo[],
  illustrations: IllustrationManifest = { images: [] }
): string {
  const byId = new Map(manifest.images.map((p) => [p.id, p]));
  const L: string[] = ["# Image review", "", GENERATED, ""];
  L.push(
    "Every pairing of a civics question and a picture, for the owner to check. `question-images.json` is marked `needsHumanReview`: a picture is shown only after the answer is graded and in Study first, but a wrong pairing would still mislead. Check that each picture fits the question and does not suggest a wrong answer.",
    ""
  );
  const mapped = questions.filter((q) => q.id in mapping.questions);
  L.push(`${mapped.length} of ${questions.length} questions have a picture.`, "");
  L.push("Write OK (or a note) in the last column once a pairing is checked.", "");
  L.push("## Federal pictures", "");
  L.push("| Question | Text | Picture | Caption | Source | Rights | Owner OK |", "|---|---|---|---|---|---|---|");
  for (const q of mapped) {
    const p = byId.get(mapping.questions[q.id] as string);
    if (p === undefined) continue;
    L.push(
      `| ${q.id} | ${cell(q.text)} | ![${cell(p.alt)}](../public/images/civics/${p.file}) \`public/images/civics/${p.file}\` | ${cell(p.caption)} | <${p.sourcePageUrl}> | ${cell(p.rights)} |  |`
    );
  }
  L.push("", "## AI illustrations (CONCEPT questions only)", "");
  const text = new Map(questions.map((q) => [q.id, q.text]));
  if (illustrations.images.length === 0) {
    L.push("None made yet. Run `node --no-warnings tools/images/generate-illustrations.mjs --run`, then review them here and set `reviewed: true` in `data/images/illustrations-manifest.json` for each one you approve.", "");
  } else {
    L.push("| Question | Text | Illustration | Caption | Model | Reviewed | Owner OK |", "|---|---|---|---|---|---|---|");
    for (const e of illustrations.images) {
      for (const q of e.questions) {
        L.push(
          `| ${q} | ${cell(text.get(q) ?? "")} | ![${cell(e.alt)}](../public/images/illustrations/${e.file}) \`public/images/illustrations/${e.file}\` | ${cell(e.caption)} | ${cell(e.model)} | ${e.reviewed ? "yes" : "no"} |  |`
        );
      }
    }
    L.push("");
  }
  const without = questions.filter((q) => !(q.id in mapping.questions) && !illustrations.images.some((e) => e.questions.includes(q.id)));
  L.push("", "## Questions without a picture", "");
  L.push(without.map((q) => q.id).join(", "), "");
  return L.join("\n");
}

export function buildTodo(todo: readonly TodoEntry[], misses: readonly MissEntry[] = []): string {
  const L: string[] = ["# Image to-do", "", GENERATED, ""];
  L.push(
    "Pictures I wanted but could not use. No other source was substituted. Fetch these by hand, check the rights statement on the page, and add them to `data/images/picks.json`.",
    ""
  );
  L.push("## Picks that failed to build", "");
  if (todo.length === 0) {
    L.push("None.", "");
  } else {
    L.push("| Wanted | Page | Why it was not saved |", "|---|---|---|");
    for (const t of todo) L.push(`| ${cell(t.wanted)} | <${t.pageUrl}> | ${cell(t.reason)} |`);
    L.push("");
  }
  L.push("## Questions with no fitting picture yet", "");
  L.push("Questions of a picture class (see `docs/image-plan.md`) for which no item from an allowed federal source fits. From `data/images/misses.json`.", "");
  if (misses.length === 0) {
    L.push("None.", "");
  } else {
    L.push("| Questions | Wanted | What was searched | Why nothing was used |", "|---|---|---|---|");
    for (const m of misses) L.push(`| ${m.questions.join(", ")} | ${cell(m.wanted)} | ${cell(m.searched)} | ${cell(m.why)} |`);
    L.push("");
  }
  return L.join("\n");
}
