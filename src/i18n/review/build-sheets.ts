/**
 * Builds the review sheets in docs/ from the locale files: one index (docs/locale-review.md)
 * and one sheet per language (docs/locale-review/<code>.md) for a native speaker to read.
 * Pure: returns text. tools/i18n/build-locale-review.mjs writes the files; a test checks that
 * the files in docs/ equal this output, so the sheets cannot go stale.
 *
 * A sheet lists key, English and translation. Disclaimer and legal lines come first (with my
 * back-translation), then lines that state a USCIS rule, then everything else.
 */
import type { LanguageCode, LanguageInfo } from "../languages.ts";
import { FIXED_TERMS, IDENTICAL_ALLOWED, type LocaleMeta } from "../locale-checks.ts";

/** Everything the sheets are built from. The caller loads it (Vite imports in tests, fs in the script). */
export interface ReviewData {
  languages: readonly LanguageInfo[];
  en: Record<string, string>;
  catalogs: Partial<Record<LanguageCode, Record<string, string>>>;
  status: Partial<Record<LanguageCode, LocaleMeta>>;
  backTranslations: {
    keys: string[];
    backTranslations: Record<string, Record<string, string>>;
    differs: Record<string, Record<string, string>>;
    fixed: { language: string; key: string; what: string }[];
  };
  viChanges: { changes: { key: string; before: string; after: string; why: string }[] };
}
const cell = (text: string): string => text.replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ");

function groups(en: Record<string, string>, legalKeys: readonly string[]): { title: string; keys: string[] }[] {
  const legal = legalKeys.filter((k) => k in en);
  const rest = Object.keys(en).filter((k) => !legal.includes(k));
  const rules = rest.filter((k) => /USCIS|uscis\.gov|passing score|answer key/i.test(en[k] as string));
  const others = rest.filter((k) => !rules.includes(k));
  return [
    { title: "1. Disclaimers, legal and privacy lines", keys: legal },
    { title: "2. Lines that mention USCIS, test rules or the answer key", keys: rules },
    { title: "3. All other lines", keys: others },
  ];
}

export const otherCodes = (data: ReviewData): LanguageCode[] => data.languages.filter((l) => l.code !== "en").map((l) => l.code);

export function sheetPath(code: string): string {
  return `docs/locale-review/${code}.md`;
}

export function buildSheet(code: LanguageCode, data: ReviewData): string {
  const { en, backTranslations } = data;
  const info = data.languages.find((l) => l.code === code)!;
  const messages = data.catalogs[code] ?? {};
  const meta = data.status[code];
  const bt = backTranslations.backTranslations[code] ?? {};
  const differs = backTranslations.differs[code] ?? {};
  const lines: string[] = [];
  lines.push(`# Locale review sheet: ${info.endonym} (${code})`, "");
  lines.push("<!-- Generated by tools/i18n/build-locale-review.mjs from the locale files. Do not edit by hand. -->", "");
  lines.push(
    `Status: ${meta?.source ?? "unknown"}. Reviewed by: ${meta?.reviewedBy ?? "nobody yet"}. Reviewed on: ${meta?.reviewedOn ?? "not yet"}.`,
    `HTML language tag: \`${info.htmlLang}\`. ${info.tier === "official" ? "USCIS publishes civics material in this language." : "Community language (no USCIS civics translation was used)."}`,
    ""
  );
  lines.push(
    "## How to review",
    "",
    "Read each row. For each translation, check that it says the same thing as the English, in words a speaker of this language would use. Mark anything stiff, wrong or unnatural. The English column is the source of truth.",
    "To record a review, fill `reviewedBy` and `reviewedOn` in `_meta` of `src/i18n/locales/" + code + ".json` and set `source` to `human-reviewed`. The AI label then disappears for this language.",
    ""
  );
  for (const group of groups(en, backTranslations.keys)) {
    if (group.keys.length === 0) continue;
    lines.push(`## ${group.title}`, "");
    const withBt = group.keys.some((k) => k in bt);
    lines.push(withBt ? "| Key | English | Translation | Back-translation (AI) |" : "| Key | English | Translation |");
    lines.push(withBt ? "|---|---|---|---|" : "|---|---|---|");
    for (const key of group.keys) {
      const flag = key in differs ? " ⚠" : "";
      const row = [`\`${key}\`${flag}`, cell(en[key] as string), cell(messages[key] ?? ""), ...(withBt ? [cell(bt[key] ?? "")] : [])];
      lines.push(`| ${row.join(" | ")} |`);
    }
    lines.push("");
  }
  const notes = Object.entries(differs);
  if (notes.length > 0) {
    lines.push("## Lines marked ⚠ (meaning differs a little)", "");
    for (const [key, note] of notes) lines.push(`- \`${key}\`: ${note}`);
    lines.push("");
  }
  return lines.join("\n");
}

export function buildIndex(data: ReviewData): string {
  const { backTranslations, viChanges } = data;
  const L: string[] = [];
  L.push("# Locale review", "");
  L.push("<!-- Generated by tools/i18n/build-locale-review.mjs. Do not edit by hand. -->", "");
  L.push(
    "The interface is offered in 14 languages. English is the source. The other 13 are **AI-generated drafts** written by the same AI that built this app. No native speaker has reviewed any of them. Each screen in those languages shows a label saying so, and every disclaimer is shown with its English text (content-safety rule 3, decisions-log section G).",
    ""
  );
  L.push("## Status", "", "| Language | Code | Source | Reviewed by | Sheet |", "|---|---|---|---|---|");
  for (const l of data.languages) {
    if (l.code === "en") {
      L.push(`| ${l.endonym} | en | source language | n/a | n/a |`);
      continue;
    }
    const meta = data.status[l.code];
    L.push(`| ${l.endonym} | ${l.code} | ${meta?.source} | ${meta?.reviewedBy ?? "nobody yet"} | [${l.code}](locale-review/${l.code}.md) |`);
  }
  L.push("", "## How a language loses the AI label", "", "A named human reviewer and an ISO review date in the `_meta` of the locale file. Nothing else removes it.", "");
  L.push("## Automated checks every locale passes", "");
  L.push(
    "Same keys as English. Same `{placeholders}`. Every number in the English line appears with the same value (digits of other scripts are read as numbers). No empty text.",
    `These terms stay as written: ${FIXED_TERMS.map((t) => `\`${t}\``).join(", ")}.`,
    `Nothing may equal the English text except: ${IDENTICAL_ALLOWED.map((k) => `\`${k}\``).join(", ")}.`,
    "The checks do not read meaning. That is what the sheets are for.",
    ""
  );
  L.push("## Choices to confirm", "");
  L.push(
    "- **Chinese is Traditional** (`zh-Hant`, shown as 中文（繁體）). It follows USCIS's Chinese materials. Simplified Chinese is not provided.",
    "- **Filipino** uses the language tag `fil`. Haitian Creole is shown as Kreyòl ayisyen. Hmong is White Hmong (RPA spelling).",
    "- **Home heading.** In every language the home heading is \"Welcome to Language Lab\" (not the English \"Welcome to the booth\"), and the word \"booth\" in the home lead is rendered as a quiet room or space. English still says \"booth\". This was decided for Vietnamese in step 5 and applied to the others to match.",
    "- **Tagalog** shows \"Sibika (Civics)\" for three labels that would otherwise equal the English.",
    "- **Dates** use the Gregorian calendar and Latin digits in every language. Where the browser has no data for the language (Hmong, Haitian Creole in current browsers), month names are English.",
    ""
  );
  L.push("## Key words by language (read these first)", "", "| Code | Civics (stage name) | Worth reviewing (badge) | Not affiliated (short disclaimer) |", "|---|---|---|---|");
  for (const code of otherCodes(data)) {
    const m = data.catalogs[code] ?? {};
    L.push(`| ${code} | ${cell(m["stage.civics.label"] ?? "")} | ${cell(m["badge.review"] ?? "")} | ${cell(m["disclaimer.short"] ?? "")} |`);
  }
  L.push("", "## Back-translation pass", "");
  L.push(
    "I translated the disclaimer, privacy and legal lines (16 keys, 13 languages) back into English and compared them with the source. This is a weak check: the same AI wrote the drafts and read them back. The back-translations are in each sheet, first section.",
    ""
  );
  L.push("### Found and fixed", "");
  for (const f of backTranslations.fixed) L.push(`- ${f.language} \`${f.key}\`: ${f.what}`);
  L.push("", "### Still differs a little", "");
  for (const [code, notes] of Object.entries(backTranslations.differs)) {
    for (const [key, note] of Object.entries(notes)) L.push(`- ${code} \`${key}\`: ${note}`);
  }
  L.push("", "### Confidence", "");
  L.push(
    "Least confident: Hmong (hmn), Lao (lo), Burmese (my), Haitian Creole (ht). Then Thai (th), Filipino (tl), Hindi (hi). I have no confidence figure for the rest: the back-translation pass found real meaning errors in Russian and Filipino too. This is my own estimate from vocabulary range and the amount of stiff phrasing I found, not a measurement.\n\nBurmese: the font stack is for Unicode Burmese. Phones that still use Zawgyi-encoded text may show garbled letters; this has not been tested.",
    ""
  );
  L.push("## Vietnamese wording pass (step 5)", "");
  L.push("The home heading, \"buồng\" and word-for-word lines. Before and after:", "");
  L.push("| Key | Before | After | Why |", "|---|---|---|---|");
  for (const c of viChanges.changes) L.push(`| \`${c.key}\` | ${cell(c.before)} | ${cell(c.after)} | ${cell(c.why)} |`);
  L.push("");
  return L.join("\n");
}
