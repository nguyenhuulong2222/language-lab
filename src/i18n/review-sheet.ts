/**
 * src/i18n/review-sheet.ts
 *
 * Builds docs/vi-locale-review.md: every interface line in English and Vietnamese, for the
 * person who reviews the Vietnamese draft. Disclaimers and legal wording come first, then
 * statements about USCIS rules and official lists, then everything else in file order.
 *
 * The sheet is generated (tools/i18n/build-vi-review.mjs) and a test checks that the file in
 * docs/ is the same as what this function builds, so the sheet cannot fall behind vi.json.
 *
 * Pure module: no DOM, no network.
 */

export interface ReviewInput {
  /** The English messages (the source). */
  en: Readonly<Record<string, string>>;
  /** The Vietnamese messages, without "_meta". */
  vi: Readonly<Record<string, string>>;
}

/** Keys that are disclaimers or legal wording: reviewed first. */
export const LEGAL_KEYS: readonly string[] = [
  "disclaimer.title",
  "disclaimer.short",
  "disclaimer.full",
  "disclaimer.report",
  "intro.notice.practice",
  "intro.notice.legal",
  "intro.notice.government",
  "intro.privacy",
  "voice.privacy",
  "n400.sample.note",
  "help.setup.2",
  "lang.interviewEnglish",
  "translation.notice",
  "partReport.scope",
  "report.n400Note",
];

/** Keys that say something about USCIS rules, the test versions or the official answers. */
export const OFFICIAL_KEYS: readonly string[] = [
  "intro.filed.legend",
  "intro.filed.before",
  "intro.filed.onOrAfter",
  "intro.filed.help",
  "compare.setting",
  "compare.vocab",
  "civics.officialNote",
  "civics.official",
  "civics.stopped.correct",
  "civics.stopped.incorrect",
  "civics.stopped.none",
  "civics.locked.title",
  "civics.locked.text",
  "intro.locked",
  "partReport.unscored.text",
  "report.profile.meta",
];

/** Words whose Vietnamese form is a choice. The reviewer confirms or replaces them. */
export const TERM_CHOICES: ReadonlyArray<readonly [english: string, vietnamese: string, note: string]> = [
  ["naturalization interview", "phỏng vấn nhập tịch", "The usual term for the interview."],
  ["civics", "civics / kiến thức công dân", "The test name is kept as \"civics\" in buttons so it matches what applicants see on uscis.gov; the long form is used in titles."],
  ["on track", "đang đi đúng hướng", "Encouraging, not a pass or fail word."],
  ["Not yet", "Chưa đúng", "Used instead of \"wrong\". Keep it gentle."],
  ["practice passing score", "số điểm đậu của bài luyện tập", "\"Đậu\" is the everyday word for passing a test."],
  ["fictional profile", "hồ sơ hư cấu", "A made-up person. Alternative: \"hồ sơ giả định\"."],
  ["A-number", "số A (A-number)", "Kept in English in brackets so the user can match it to the form."],
  ["TAKE (tape counter)", "TAKE", "A decorative label of the booth design; deliberately not translated."],
  ["USCIS, DHS, N-400, uscis.gov", "(unchanged)", "Names and forms are not translated."],
  ["Allow (browser button)", "Cho phép", "The browser or phone shows its own button in the device language."],
];

const cell = (text: string): string => text.replace(/\|/g, "\\|").replace(/\n/g, " ");

function table(keys: readonly string[], input: ReviewInput): string[] {
  const rows = ["| Key | English | Vietnamese |", "|---|---|---|"];
  for (const key of keys) {
    rows.push(`| \`${key}\` | ${cell(input.en[key] ?? "")} | ${cell(input.vi[key] ?? "")} |`);
  }
  return rows;
}

/** The whole review sheet as Markdown. */
export function buildReviewSheet(input: ReviewInput): string {
  const enKeys = Object.keys(input.en);
  const first = LEGAL_KEYS.filter((k) => k in input.en);
  const second = OFFICIAL_KEYS.filter((k) => k in input.en && !first.includes(k));
  const rest = enKeys.filter((k) => !first.includes(k) && !second.includes(k));

  const lines: string[] = [
    "# Vietnamese interface: review sheet",
    "",
    "Generated from `src/i18n/locales/en.json` and `src/i18n/locales/vi.json` by",
    "`node --no-warnings tools/i18n/build-vi-review.mjs`. Do not edit this file by hand: a test",
    "fails when it differs from what the script builds.",
    "",
    "## Status",
    "",
    "`vi.json` is a **draft written by an AI assistant**, not by a translator. It is marked",
    "`needsHumanReview: true` in its `_meta` entry. While that flag is true:",
    "",
    "- the Vietnamese option is available in the development server (`npm run dev`);",
    "- the Vietnamese option is **hidden in a production build** (`npm run build`, the deployed site).",
    "",
    "After you have reviewed every line below, change `needsHumanReview` to `false` in",
    "`src/i18n/locales/vi.json` and regenerate this sheet. Nothing else needs to change.",
    "",
    "What stays in English on purpose: civics questions and answers, reading and writing sentences,",
    "N-400 questions and sample answers, and the sentences the engine builds for the full report",
    "(stage summaries and review items). The screen says so: \"The real interview is in English.\"",
    "",
    "Every line keeps the same `{placeholders}` as the English line (a test checks this).",
    "",
    "## Terms to confirm",
    "",
    "| English | Vietnamese used | Note |",
    "|---|---|---|",
    ...TERM_CHOICES.map(([en, vi, note]) => `| ${cell(en)} | ${cell(vi)} | ${cell(note)} |`),
    "",
    `## 1. Disclaimers and legal wording (${first.length} lines)`,
    "",
    "Review these first. They say what the tool is not: not legal advice, not a government service,",
    "not affiliated with USCIS, and that nothing real should be typed.",
    "",
    ...table(first, input),
    "",
    `## 2. Statements about USCIS rules and official lists (${second.length} lines)`,
    "",
    ...table(second, input),
    "",
    `## 3. All other interface text (${rest.length} lines)`,
    "",
    ...table(rest, input),
    "",
  ];
  return lines.join("\n");
}
